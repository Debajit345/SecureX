create table if not exists public.reports (
    id bigint generated by default as identity primary key,
    url text not null check (char_length(url) <= 2048),
    category text not null check (category in ('phishing', 'impersonation', 'payment scam', 'malware', 'other')),
    note text not null default '' check (char_length(note) <= 300),
    created_at timestamptz not null default now()
);
create index if not exists reports_url_created_at_idx on public.reports (url, created_at desc);
alter table public.reports enable row level security;
revoke all on public.reports from anon, authenticated;
grant usage on schema public to anon;
grant select (url, category, created_at) on public.reports to anon;
grant insert (url, category, note) on public.reports to anon;

create policy "Community can read report signals"
    on public.reports for select to anon using (true);
create policy "Community can submit reports"
    on public.reports for insert to anon
    with check (
        char_length(url) between 3 and 2048
        and category in ('phishing', 'impersonation', 'payment scam', 'malware', 'other')
        and char_length(note) <= 300
    );
